/**
 * Deterministic pseudo random number generation.
 * Every procedural system derives its randomness from a seeded {@link Rng}
 * so that the same seed always reproduces the same island and ecosystem.
 */

/** Hash an arbitrary string into a 32-bit unsigned seed (FNV-1a). */
export function hashString(str: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Turn user input (number or text) into a numeric seed. */
export function parseSeed(input: string | number): number {
  if (typeof input === 'number') return input >>> 0;
  const trimmed = input.trim();
  if (/^\d+$/.test(trimmed)) return Number(trimmed) >>> 0;
  return hashString(trimmed);
}

/** Stateless integer hash for (x, y, seed) triples – used for per-cell variation. */
export function hash2(x: number, y: number, seed: number): number {
  let h = Math.imul(x | 0, 0x27d4eb2d) ^ Math.imul(y | 0, 0x165667b1) ^ Math.imul(seed | 0, 0x9e3779b1);
  h = Math.imul(h ^ (h >>> 15), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

/** Mulberry32 – tiny, fast, good-enough PRNG with serialisable state. */
export class Rng {
  private s: number;

  constructor(seed: number) {
    this.s = seed >>> 0;
  }

  get state(): number {
    return this.s;
  }

  set state(v: number) {
    this.s = v >>> 0;
  }

  /** Uniform float in [0, 1). */
  next(): number {
    this.s = (this.s + 0x6d2b79f5) >>> 0;
    let t = this.s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  range(min: number, max: number): number {
    return min + (max - min) * this.next();
  }

  int(min: number, maxInclusive: number): number {
    return min + Math.floor(this.next() * (maxInclusive - min + 1));
  }

  chance(p: number): boolean {
    return this.next() < p;
  }

  pick<T>(arr: readonly T[]): T {
    return arr[Math.floor(this.next() * arr.length)];
  }

  /** Derive an independent generator for a named sub-system. */
  fork(label: string): Rng {
    return new Rng((this.s ^ hashString(label)) >>> 0);
  }
}
